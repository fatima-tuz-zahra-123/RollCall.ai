    start = int(start_sec * fps) if start_sec is not None else total // 2
    n_max = int(duration_sec * fps) if duration_sec else total - start
    cap.set(cv2.CAP_PROP_POS_FRAMES, start)
    n = calls = dup = unk = 0; t0 = time.time()
    while n < n_max:
        ok, frame = cap.read()
        if not ok: break
        n += 1
